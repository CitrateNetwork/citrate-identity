#!/usr/bin/env bash
# Stage the COMMERCIAL-SAFE document-authenticity datasets for AV-S4 calibration:
#   - IDNet     (CC0 / public domain)      — synthetic forged IDs → forged-accept metric
#   - MIDV-Holo (CC BY-SA 2.5, commercial) — genuine + hologram-attack docs → genuine-pass
# Both are fully synthetic (no real PII → no BIPA/GDPR blocker) and commercial-usable.
# IDNet integrity is verified against Zenodo's PUBLISHED MD5 checksums (baked in below);
# MIDV-Holo provenance is recorded. Fail-closed on mismatch. bash 3.2-safe (macOS + Linux).
#
# SIZE: this Zenodo record (IDNet part 3) is 46.5GB (california 18.7 / lva 17.5 / rus 6.0 /
# svk 4.3). The FULL IDNet is ~400GB across multiple Zenodo records. Default here stages a
# ~10GB SUBSET (rus+svk) for a first calibration pass; set IDNET_FILES to stage more.
# Run this on the calibration HOST (with disk + bandwidth), not a laptop.
set -euo pipefail
DEST="${KYC_CALIB_DIR:?set KYC_CALIB_DIR — where to stage the document datasets}"
mkdir -p "$DEST"

md5_of()    { if command -v md5sum   >/dev/null 2>&1; then md5sum "$1"    | awk '{print $1}'; else md5 -q "$1"; fi; }
sha256_of() { if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1" | awk '{print $1}'; else shasum -a 256 "$1" | awk '{print $1}'; fi; }

# --- IDNet (CC0) — Zenodo record 10570622. Per-file MD5 pins from the canonical record ---
IDNET_BASE="https://zenodo.org/records/10570622/files"
idnet_md5() { # published MD5 for each archive (verified 2026-07-19 from the Zenodo API)
  case "$1" in
    rus.zip)        echo 1cd8967bc5750df80da8c5405b247d19 ;;
    svk.zip)        echo 36c0068547a27e909f1fce32f9e10ee6 ;;
    lva.zip)        echo 3270e5ae4fa69cad138d50f75361fad8 ;;
    california.zip) echo 750d90c4eea247477ab4e4b09e9a8921 ;;
    *) echo "" ;;
  esac
}
# Default subset (~10GB). Override e.g. IDNET_FILES="rus.zip svk.zip lva.zip california.zip".
IDNET_FILES="${IDNET_FILES:-rus.zip svk.zip}"

: > "$DEST/DOC_DATASETS.lock"
{
  echo "# VERI calibration doc-dataset lock — generated by download_doc_datasets.sh"
  echo "# <sha256>  <relpath>  <license>  (md5 verified against source at fetch)"
} >> "$DEST/DOC_DATASETS.lock"

mkdir -p "$DEST/idnet"
for f in $IDNET_FILES; do
  want="$(idnet_md5 "$f")"
  [ -n "$want" ] || { echo "[data] FATAL: unknown IDNet file '$f' (no pinned MD5)" >&2; exit 1; }
  echo "[data] fetching IDNet/$f (CC0) from Zenodo…"
  curl -fsSL "$IDNET_BASE/$f?download=1" -o "$DEST/idnet/$f"
  got="$(md5_of "$DEST/idnet/$f")"
  if [ "$got" != "$want" ]; then
    echo "[data] FATAL: MD5 mismatch for $f (expected $want, got $got)" >&2; exit 1
  fi
  echo "[data] OK  idnet/$f  md5=$got"
  echo "$(sha256_of "$DEST/idnet/$f")  idnet/$f  CC0" >> "$DEST/DOC_DATASETS.lock"
done

# --- MIDV-Holo (CC BY-SA 2.5) — Smart Engines FTP (recursive tree, ~several GB) ---
# ATTRIBUTION REQUIRED (CC BY-SA 2.5): credit Smart Engines; faces are from Generated Photos
# (generated.photos) — include their attribution in any derivative work.
if command -v wget >/dev/null 2>&1; then
  echo "[data] fetching MIDV-Holo (CC BY-SA 2.5) from ftp://smartengines.com/midv-holo …"
  wget -r -np -nH --cut-dirs=1 -q -P "$DEST/midv-holo" "ftp://smartengines.com/midv-holo/" \
    && echo "[data] OK  midv-holo/ (record attribution — see below)" \
    || echo "[data] WARN: MIDV-Holo FTP fetch failed; retry with an FTP client from ftp://smartengines.com/midv-holo" >&2
else
  echo "[data] wget not found — MIDV-Holo is a recursive FTP tree. Install wget, or use an" >&2
  echo "       FTP client against ftp://smartengines.com/midv-holo (then re-run to lock it)." >&2
fi
{
  echo "# midv-holo/  CC-BY-SA-2.5  source=ftp://smartengines.com/midv-holo"
  echo "#   attribution: Smart Engines; faces from Generated Photos (generated.photos)"
} >> "$DEST/DOC_DATASETS.lock"

echo "[data] wrote $DEST/DOC_DATASETS.lock"
echo "[data] done → $DEST"
echo "[data] NEXT: record provenance (source URL, license, download date, frozen-split hash,"
echo "[data]       + MIDV-Holo attribution) in calibration/DATASETS.md per the checklist."
