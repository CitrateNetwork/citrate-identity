#!/usr/bin/env bash
# Fetch + SHA-pin the COMMERCIAL-SAFE document-authenticity datasets for AV-S4 calibration:
#   - IDNet     (CC0 / public domain)      — synthetic forged IDs, forged-accept metric
#   - MIDV-Holo (CC BY-SA 2.5, commercial) — genuine + hologram-attack docs, genuine-pass
# Both are fully synthetic (no real PII → no BIPA/GDPR blocker) and licensed for commercial
# use, so unlike the research-only PAD sets they can feed a shipped pipeline (with counsel's
# ok). Every artifact hash is REQUIRED and fail-closed (mirrors ../download_models.sh).
#
# The operator pins each SHA once from a trusted fetch (the archives are large — IDNet is
# ~490GB — so they are not committed and their hashes are not hardcoded here). Writes
# DOC_DATASETS.lock for a later integrity re-check.
set -euo pipefail
DEST="${KYC_CALIB_DIR:?set KYC_CALIB_DIR — where to stage the document datasets}"
mkdir -p "$DEST"

sha256_of() {
  if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1" | awk '{print $1}';
  else shasum -a 256 "$1" | awk '{print $1}'; fi
}
require_sha() { # $1 file, $2 expected
  local got; got="$(sha256_of "$1")"
  if [ "$got" != "$2" ]; then
    echo "[data] FATAL: SHA256 mismatch for $1 (expected $2, got $got)" >&2; exit 1
  fi
  echo "[data] OK  $(basename "$1")  $got"
}

# --- IDNet (CC0) — Zenodo record 10570622 ---
# Reference: https://zenodo.org/records/10570622  (confirm the exact file name + size there).
# ~490GB — ensure the volume has room. Pin the archive SHA before first use.
: "${IDNET_URL:?set IDNET_URL to the IDNet archive on Zenodo (record 10570622)}"
: "${IDNET_SHA256:?set IDNET_SHA256 — pin it from a trusted fetch}"
echo "[data] fetching IDNet (CC0) — this is large (~490GB)…"
curl -fsSL "$IDNET_URL" -o "$DEST/idnet.zip"
require_sha "$DEST/idnet.zip" "$IDNET_SHA256"

# --- MIDV-Holo (CC BY-SA 2.5) — Smart Engines ---
# Reference: https://github.com/SmartEngines/midv-holo (follow its download link/terms).
# CC BY-SA 2.5: attribution + share-alike required — record attribution in provenance notes.
: "${MIDV_HOLO_URL:?set MIDV_HOLO_URL to the MIDV-Holo archive}"
: "${MIDV_HOLO_SHA256:?set MIDV_HOLO_SHA256 — pin it from a trusted fetch}"
echo "[data] fetching MIDV-Holo (CC BY-SA 2.5)…"
curl -fsSL "$MIDV_HOLO_URL" -o "$DEST/midv-holo.zip"
require_sha "$DEST/midv-holo.zip" "$MIDV_HOLO_SHA256"

# --- lockfile for later integrity re-check ---
{
  echo "# VERI calibration doc-dataset lock — generated by download_doc_datasets.sh."
  echo "# sha256  relpath  license"
  echo "$IDNET_SHA256  idnet.zip  CC0"
  echo "$MIDV_HOLO_SHA256  midv-holo.zip  CC-BY-SA-2.5"
} > "$DEST/DOC_DATASETS.lock"
echo "[data] wrote $DEST/DOC_DATASETS.lock"
echo "[data] done → $DEST"
echo "[data] REMINDER: record provenance (source URL, license, download date, frozen-split"
echo "[data]           hash) in calibration/DATASETS.md per the provenance checklist."
